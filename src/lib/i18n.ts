// Languages that commonly use 12-hour (AM/PM) time format
const LANGUAGES_WITH_12H: Language[] = ['en', 'tl', 'haw'];

// Check if a language should default to 24-hour time
export function shouldUse24Hour(lang: Language): boolean {
  return !LANGUAGES_WITH_12H.includes(lang);
}

// Map of default label keys to translation keys
const DEFAULT_LABEL_KEYS: Record<string, keyof TranslationKeys> = {
  'Wake': 'wake',
  'Work': 'work',
  'Appt': 'appointment',
};

// Translate a label if it's a default one, otherwise return as-is
export function translateLabel(label: string, lang: Language): string {
  const t = getTranslations(lang);
  const key = DEFAULT_LABEL_KEYS[label];
  if (key) {
    return t[key] as string;
  }
  return label;
}

// Get the English key for a translated label (for storing)
export function getLabelKey(translatedLabel: string, lang: Language): string {
  const t = getTranslations(lang);
  for (const [englishKey, translationKey] of Object.entries(DEFAULT_LABEL_KEYS)) {
    if (t[translationKey] === translatedLabel) {
      return englishKey;
    }
  }
  return translatedLabel; // Custom label, return as-is
}
